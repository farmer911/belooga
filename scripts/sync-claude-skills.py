#!/usr/bin/env python3
"""
sync-claude-skills.py - expose .agents/skills to Claude Code as .claude/skills/<name>/SKILL.md stubs.

Why stubs instead of a symlink: git symlinks check out as plain text files on Windows
without core.symlinks/Developer Mode, which silently breaks Claude Code there. Each stub
copies the canonical frontmatter (name, description, argument-hint) so Claude Code can
route to it, and its body points at the canonical .agents/skills/<name>/SKILL.md.

Usage:
    python3 scripts/sync-claude-skills.py           # write/update/prune stubs
    python3 scripts/sync-claude-skills.py --check   # exit 1 if stubs are out of sync (lint-skills.py runs this)
Stdlib only (CI runs gate scripts with `python3 -I -S`).
"""
import json
import re
import shutil
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")  # Windows pipes default to cp1252

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / ".agents" / "skills"
DST = ROOT / ".claude" / "skills"
KEYS = ("name", "description", "argument-hint")


def frontmatter(text: str) -> dict:
    """Minimal parser for the frontmatter shapes used in .agents/skills (scalars and folded >- blocks)."""
    m = re.match(r"---\r?\n(.*?)\r?\n---", text, re.S)
    data, key = {}, None
    for line in (m.group(1).splitlines() if m else []):
        if line[:1] in (" ", "\t") and key:
            data[key] = (data[key] + " " + line.strip()).strip()
        elif ":" in line:
            key, val = (s.strip() for s in line.split(":", 1))
            val = val.strip()
            data[key] = "" if val in (">", ">-", "|", "|-") else val.strip("\"'")
    return data


def stub(name: str, fm: dict) -> str:
    head = "\n".join(f"{k}: {json.dumps(fm[k], ensure_ascii=False)}" for k in KEYS if fm.get(k))
    return (
        f"---\n{head}\n---\n\n"
        f"<!-- Generated by scripts/sync-claude-skills.py from .agents/skills/{name}/SKILL.md. Do not edit. -->\n"
        f"Canonical skill: `.agents/skills/{name}/SKILL.md`. Read that file in full and follow it.\n"
        f"Paths to `references/` or `scripts/` in it are relative to `.agents/skills/{name}/`.\n"
    )


def expected() -> dict:
    out = {}
    for skill in sorted(SRC.glob("*/SKILL.md")):
        name = skill.parent.name
        out[DST / name / "SKILL.md"] = stub(name, frontmatter(skill.read_text(encoding="utf-8")))
    return out


def main() -> int:
    want = expected()
    have = {p for p in DST.glob("*/SKILL.md")} if DST.exists() else set()
    stale = [p for p, body in want.items() if not p.exists() or p.read_text(encoding="utf-8") != body]
    extra = sorted(have - set(want))
    if "--check" in sys.argv:
        for p in stale + extra:
            print(f"  out of sync: {p.relative_to(ROOT).as_posix()}")
        if stale or extra:
            print("Run: python3 scripts/sync-claude-skills.py")
        return 1 if stale or extra else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(want[p], encoding="utf-8", newline="\n")
    for p in extra:
        shutil.rmtree(p.parent)
    print(f"{len(want)} skill stubs in {DST.relative_to(ROOT).as_posix()} ({len(stale)} written, {len(extra)} pruned)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
